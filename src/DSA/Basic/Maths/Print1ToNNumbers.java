package DSA.Basic.Maths;

public class Print1ToNNumbers {

    public static void main(String[] args){
        int n=10;
        for(int i=1;i<=n;i++){
            System.out.print(" "+i);
        }
        System.out.println(" ");
        int i=1;
        while (i<=n){
            System.out.print(" "+i);
            i++;
        }
    }
}
